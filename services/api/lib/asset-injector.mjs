/**
 * Deterministic uploaded-asset display injector.
 *
 * The problem it solves: a template author — the Studio's LLM, or an imported
 * customer template — may build a beautiful home page out of decorative CSS and
 * emoji and never reference the customer's uploaded photos at all. The files
 * are on disk and `src/config/assets.generated.ts` is written faithfully, but
 * nothing in the template renders them, so the customer sees no photos. Asking
 * the model to "consume siteAssets" is not reliable: it designs around shapes.
 *
 * So after assembly we GUARANTEE the uploads appear, without depending on the
 * template. We use only structural anchors every d4-derived template has:
 *   - `{children}` in src/app/layout.tsx  → mount a home-page showcase there
 *   - `{siteConfig.name}` in the header    → weave the logo in beside the name
 *
 * If the template ALREADY consumes siteAssets (the catalog d4-site-template and
 * its modules do), we do nothing: it displays the uploads its own, designed way
 * and we must not double-render.
 */
import fs from 'node:fs';
import path from 'node:path';

const CODE_EXT = /\.(tsx|ts|jsx|js)$/;

function walkFiles(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walkFiles(p, out);
    else out.push(p);
  }
  return out;
}

/** True when any source file (other than the generated map itself) already
 *  reads the uploaded assets — meaning the template honors the contract. */
function templateConsumesAssets(srcDir) {
  for (const f of walkFiles(srcDir)) {
    if (!CODE_EXT.test(f)) continue;
    if (f.replace(/\\/g, '/').endsWith('config/assets.generated.ts')) continue;
    const t = fs.readFileSync(f, 'utf8');
    if (t.includes('assets.generated') || t.includes('siteAssets')) return true;
  }
  return false;
}

// The showcase: self-contained, styled with d4 theme tokens (present in every
// d4-derived template), shown only on the home page, and rendering only the
// compartments that actually have uploads. Our code, not the template's.
const SHOWCASE = `"use client";

/**
 * GENERATED by Stardrive. Displays the customer's uploaded photos on the home
 * page when the chosen template does not show them itself. Regenerated on every
 * assembly; safe to delete if you wire the uploads into your own design.
 */
import { usePathname } from "next/navigation";
import { siteAssets } from "@/config/assets.generated";

export function StardriveShowcase() {
  const pathname = usePathname();
  if (pathname !== "/") return null;

  const hero = siteAssets.hero?.[0];
  const gallery = siteAssets.gallery ?? [];
  const about = siteAssets.about ?? [];
  const team = siteAssets.team ?? [];
  if (!hero && gallery.length === 0 && about.length === 0 && team.length === 0) {
    return null;
  }

  return (
    <section aria-label="Featured imagery" className="border-t border-heading/10 bg-surface">
      <div className="mx-auto max-w-6xl px-4 py-16 sm:px-6">
        {hero ? (
          <div className="mb-12">
            {/* eslint-disable-next-line @next/next/no-img-element */}
            <img src={hero} alt="" className="max-h-[460px] w-full rounded-2xl object-cover" />
          </div>
        ) : null}

        {gallery.length > 0 ? (
          <div className="mb-14">
            <h2 className="text-2xl font-bold text-heading">Gallery</h2>
            <div className="mt-5 grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
              {gallery.map((src) => (
                <div key={src}>
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src={src} alt="" className="h-64 w-full rounded-xl object-cover" />
                </div>
              ))}
            </div>
          </div>
        ) : null}

        {about.length > 0 ? (
          <div className="mb-14">
            <h2 className="text-2xl font-bold text-heading">About</h2>
            <div className="mt-5 grid gap-4 sm:grid-cols-2">
              {about.map((src) => (
                <div key={src}>
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src={src} alt="" className="max-h-80 w-full rounded-xl object-cover" />
                </div>
              ))}
            </div>
          </div>
        ) : null}

        {team.length > 0 ? (
          <div>
            <h2 className="text-2xl font-bold text-heading">Team</h2>
            <div className="mt-5 flex flex-wrap gap-4">
              {team.map((src) => (
                <div key={src}>
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src={src} alt="" className="h-28 w-28 rounded-full object-cover" />
                </div>
              ))}
            </div>
          </div>
        ) : null}
      </div>
    </section>
  );
}
`;

/** Mount <StardriveShowcase/> right after {children} in the root layout. */
function injectShowcaseIntoLayout(srcDir) {
  const layoutPath = path.join(srcDir, 'app', 'layout.tsx');
  if (!fs.existsSync(layoutPath)) return false;
  let t = fs.readFileSync(layoutPath, 'utf8');
  if (t.includes('StardriveShowcase')) return true;
  if (!t.includes('{children}')) return false; // no safe anchor — leave untouched
  t = t.replace(/^(import[^\n]*\n)/m, '$1import { StardriveShowcase } from "@/components/StardriveShowcase";\n');
  t = t.replace('{children}', '{children}\n        <StardriveShowcase />');
  fs.writeFileSync(layoutPath, t);
  return true;
}

/** Weave the uploaded logo into the header, right before the site name. */
function injectLogoIntoHeader(srcDir) {
  const headers = walkFiles(srcDir).filter(
    (f) => /Header[^\\/]*\.tsx$/.test(f) && fs.readFileSync(f, 'utf8').includes('{siteConfig.name}')
  );
  const headerPath = headers[0];
  if (!headerPath) return false;
  let t = fs.readFileSync(headerPath, 'utf8');
  if (t.includes('assets.generated')) return true;
  t = t.replace(/^(import[^\n]*\n)/m, '$1import { siteAssets } from "@/config/assets.generated";\n');
  t = t.replace(
    '{siteConfig.name}',
    `{siteAssets.logo?.[0] ? (
              // eslint-disable-next-line @next/next/no-img-element
              <img src={siteAssets.logo[0]} alt="" className="mr-2.5 inline-block h-11 w-auto max-w-[200px] object-contain align-middle" />
            ) : null}
            {siteConfig.name}`
  );
  fs.writeFileSync(headerPath, t);
  return true;
}

/**
 * Ensure the customer's uploads DISPLAY in the assembled site at `outDir`.
 * No-op when the template already consumes siteAssets. Returns what it did.
 */
export function injectAssetDisplay({ outDir }) {
  const srcDir = path.join(outDir, 'src');
  if (!fs.existsSync(srcDir)) return { injected: false, reason: 'no src dir' };
  if (templateConsumesAssets(srcDir)) {
    return { injected: false, reason: 'template displays uploads itself' };
  }

  const compDir = path.join(srcDir, 'components');
  fs.mkdirSync(compDir, { recursive: true });
  const showcasePath = path.join(compDir, 'StardriveShowcase.tsx');
  fs.writeFileSync(showcasePath, SHOWCASE);

  const showcase = injectShowcaseIntoLayout(srcDir);
  if (!showcase) fs.rmSync(showcasePath, { force: true }); // no mount point — don't leave it
  const logo = injectLogoIntoHeader(srcDir);

  return { injected: showcase || logo, showcase, logo };
}
