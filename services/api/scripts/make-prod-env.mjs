#!/usr/bin/env node
/**
 * Build `prod.env` from `docs/prod.env.example`, generating the two values
 * nobody issues you.
 *
 *   node services/api/scripts/make-prod-env.mjs
 *   node services/api/scripts/make-prod-env.mjs --print-secret   (see it once)
 *
 * STARDRIVE_SECRET and STARDRIVE_OPS_TOKEN are not credentials you fetch from
 * a dashboard. They are 32 random bytes whose only property is being the same
 * string tomorrow that they are today, so the sensible thing is to generate
 * them and never look at them.
 *
 * They are written straight to the file rather than printed, so they do not
 * sit in terminal scrollback, a shell history, or whatever is recording the
 * session. Pass --print-secret when you are ready to copy STARDRIVE_SECRET
 * into your password manager, which you should do the day it exists: it
 * encrypts every licensee's hosting tokens, and a restore without it gives you
 * accounts and sites whose credentials are all dead.
 *
 * REFUSES to overwrite an existing prod.env. Regenerating over a live secret
 * would be indistinguishable from losing it.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..');
const EXAMPLE = path.join(ROOT, 'docs', 'prod.env.example');
const TARGET = path.join(ROOT, 'prod.env');

const args = process.argv.slice(2);
const printSecret = args.includes('--print-secret');

if (!fs.existsSync(EXAMPLE)) {
  console.error(`Cannot find ${path.relative(ROOT, EXAMPLE)}. Run this from a checkout.`);
  process.exit(1);
}

if (fs.existsSync(TARGET)) {
  console.error('prod.env already exists, and this script will not overwrite it.');
  console.error('');
  console.error('  If it holds a STARDRIVE_SECRET a deployment has ever used, replacing it');
  console.error('  is the same as losing it: every stored hosting token and every per-site');
  console.error('  key becomes undecryptable. Move the file aside yourself if you are sure.');
  process.exit(1);
}

/** 32 bytes, hex. Long enough that guessing is not a strategy. */
const gen = () => crypto.randomBytes(32).toString('hex');
const secret = gen();
const opsToken = gen();

// Fill only the two blanks we can fill. Everything else stays empty on
// purpose: a placeholder that looks like a key is worse than an empty one,
// because the service treats "set" as "working" and stops saying it is off.
const filled = fs.readFileSync(EXAMPLE, 'utf-8')
  .replace(/^STARDRIVE_SECRET=$/m, `STARDRIVE_SECRET=${secret}`)
  .replace(/^STARDRIVE_OPS_TOKEN=$/m, `STARDRIVE_OPS_TOKEN=${opsToken}`)
  .replace(/^# Copy to `prod.env`[\s\S]*?^# not, so NEVER put a real value in here\.$/m,
    '# Generated by services/api/scripts/make-prod-env.mjs.\n'
    + '# This file holds real secrets and is gitignored. Do not commit it, do not\n'
    + '# paste it into a chat, and keep STARDRIVE_SECRET in a password manager too.');

// Never write a file whose required secret is blank. If the example is edited
// so a placeholder line no longer matches, the substitution above quietly does
// nothing, and the failure mode is a deployment that generates its own
// var/secret.key and looks fine until the first restore.
for (const [name, value] of [['STARDRIVE_SECRET', secret], ['STARDRIVE_OPS_TOKEN', opsToken]]) {
  if (!filled.includes(`${name}=${value}`)) {
    console.error(`Could not fill ${name}: docs/prod.env.example has no bare "${name}=" line to replace.`);
    console.error('Nothing was written. Fix the example rather than hand-editing prod.env.');
    process.exit(1);
  }
}

fs.writeFileSync(TARGET, filled, { mode: 0o600 });

console.log('Wrote prod.env (mode 0600, gitignored).');
console.log('');
console.log('  STARDRIVE_SECRET      generated');
console.log('  STARDRIVE_OPS_TOKEN   generated');
console.log('');
console.log('Still yours to fetch, and the file says where each comes from:');
console.log('  STARDRIVE_LLM_KEY     platform.openai.com, API keys (needs credit on the account)');
console.log('  RESEND_API_KEY        resend.com, API keys (verify your sending domain too)');
console.log('  STARDRIVE_LEADS_TO    an inbox you read');
console.log('');
if (printSecret) {
  console.log('STARDRIVE_SECRET, for your password manager:');
  console.log(secret);
} else {
  console.log('Back up STARDRIVE_SECRET to a password manager NOW, separately from any');
  console.log('backup of the data. Re-run with --print-secret to see it, or read it out');
  console.log('of prod.env. Losing it loses every stored hosting token you ever hold.');
}
